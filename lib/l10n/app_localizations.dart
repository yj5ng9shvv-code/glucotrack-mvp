        '${t('marketingFamilyTitle')}. ${t('marketingFamilyText')}',
        '${t('marketingSosTitle')}. ${t('marketingSosText')}',
        t('marketingMoreText'),
        t('marketingFinalText'),
      ].join('\n\n');

