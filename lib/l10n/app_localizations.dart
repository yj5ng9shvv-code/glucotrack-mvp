  static const _fallback = 'en';
  static final _brokenTranslationMarker = RegExp(r'ЗКСКПХ\d+ККСЗ');

  String t(String key) {
    final directPatientCard = patientCardTranslations[languageCode]?[key] ??
        patientCardTranslations[_fallback]?[key];
    if (directPatientCard != null) return directPatientCard;
    final directNavigation = navigationTranslations[languageCode]?[key] ??
        navigationTranslations[_fallback]?[key];
    if (directNavigation != null) return directNavigation;
    final directSosPublicCard = sosPublicCardTranslations[languageCode]?[key] ??
        sosPublicCardTranslations[_fallback]?[key];
    if (directSosPublicCard != null) return directSosPublicCard;
    final directSosNotice = sosNoticeTranslations[languageCode]?[key] ??
        sosNoticeTranslations[_fallback]?[key];
    if (directSosNotice != null) return directSosNotice;
    final directFamilyAccess = familyAccessTranslations[languageCode]?[key] ??
        familyAccessTranslations[_fallback]?[key];
    if (directFamilyAccess != null) return directFamilyAccess;
    final alias = _legacyKeyAliases[key];
    if (alias != null) {
      final aliased = t(alias);
      if (aliased != alias) return aliased;
    }
    if (key == 'currentGlucose') {
      final local = _strings[languageCode]?[key];
      if (local != null) return local;
      final family =
          familyAccessTranslations[languageCode]?['family.currentGlucose'];
      if (family != null) return family;
    }
    final homeScreen = homeScreenTranslations[languageCode]?[key] ??
        homeScreenTranslations[_fallback]?[key];
    if (homeScreen != null) return homeScreen;
    final homeCommon = homeCommonTranslations[languageCode]?[key] ??
        homeCommonTranslations[_fallback]?[key];
    if (homeCommon != null) return homeCommon;
    if (key == 'kcal') {
      final translated = coreTranslation(languageCode, key, const [
        'full',
        'compact',
      ]);
      if (translated != null && translated != key) return translated;
      final local = _strings[languageCode]?[key];
      if (local != null && local != key) return local;
      return _strings[_fallback]?[key] ?? key;
    }
    if (key == 'marketingAboutText') return marketingAboutText();
    if (key == 'networkUnavailable') {
      return networkErrorTranslations[languageCode] ??
          networkErrorTranslations[_fallback] ??
          bundled_network_errors.networkErrorTranslations[languageCode] ??
          bundled_network_errors.networkErrorTranslations[_fallback]!;
    }
    final aiAssistant = aiAssistantTranslations[languageCode]?[key] ??
        aiAssistantTranslations[_fallback]?[key];
    if (aiAssistant != null) return aiAssistant;
    final criticalModule = criticalModuleTranslations[languageCode]?[key] ??
        criticalModuleTranslations[_fallback]?[key];
    if (criticalModule != null) return criticalModule;
    final navigation = navigationTranslations[languageCode]?[key] ??
        navigationTranslations[_fallback]?[key];
    if (navigation != null) return navigation;
    final profile = profileExtraTranslations[languageCode]?[key] ??
        profileExtraTranslations[_fallback]?[key] ??
        profileTranslations[languageCode]?[key] ??
        profileTranslations[_fallback]?[key];
    if (profile != null) return profile;
    final patientCard = patientCardTranslations[languageCode]?[key] ??
        patientCardTranslations[_fallback]?[key];
    if (patientCard != null) return patientCard;
    final voicePermission = voicePermissionTranslations[languageCode]?[key] ??
        voicePermissionTranslations[_fallback]?[key];
    if (voicePermission != null) return voicePermission;
    final voiceAssistant = voiceAssistantTranslations[languageCode]?[key] ??
        voiceAssistantTranslations[_fallback]?[key];
    if (voiceAssistant != null) return voiceAssistant;
    final diaryVoice = diaryVoiceTranslations[languageCode]?[key] ??
        diaryVoiceTranslations[_fallback]?[key];
    if (diaryVoice != null) return diaryVoice;
    final authAction = authActionTranslations[languageCode]?[key] ??
        authActionTranslations[_fallback]?[key];
    if (authAction != null) return authAction;
    final premium = premiumTranslations[languageCode]?[key] ??
        premiumTranslations[_fallback]?[key];
    if (premium != null) return premium;
    final device = deviceTranslations[languageCode]?[key] ??
        deviceTranslations[_fallback]?[key];
    if (device != null) return device;
    final passwordRecovery = passwordRecoveryTranslations[languageCode]?[key] ??
        passwordRecoveryTranslations[_fallback]?[key];
    if (passwordRecovery != null) return passwordRecovery;
    final sosAction = bundled_sos_actions.sosActionTranslations[languageCode]
            ?[key] ??
        _semanticFallbacks[languageCode]?[key];
    if (sosAction != null) return sosAction;
    final emailVerification = bundled_email_verification
            .emailVerificationTranslations[languageCode]?[key] ??
        bundled_email_verification.emailVerificationTranslations[_fallback]
            ?[key];
    if (emailVerification != null) return emailVerification;
    final familyTranslation = _familyTranslations[languageCode]?[key];
    if (familyTranslation != null) return familyTranslation;
    final sosUiTranslation = _sosUiTranslations[languageCode]?[key];
    if (sosUiTranslation != null) return sosUiTranslation;
    final sosUiExtraTranslation = _sosUiExtraTranslation(languageCode, key);
    if (sosUiExtraTranslation != null) return sosUiExtraTranslation;
    final sosCoreTranslation = _sosCoreTranslation(languageCode, key);
    if (sosCoreTranslation != null) return sosCoreTranslation;
    final sosSource = _sosKeySources[key];
    if (sosSource != null) return literal(sosSource);
    final familySource = _familyKeySources[key];
    if (familySource != null) return literal(familySource);
    final legacySource =
        uiKeySources[key] ?? bundled_ui_sources.uiKeySources[key];
    if (legacySource != null) return literal(legacySource);
    final value = coreTranslation(languageCode, key, const [
          'authError',
          'sosAction',
          'authAction',
          'device',
          'passwordRecovery',
          'emailVerification',
          'voiceAssistant',
          'full',
          'compact',
          'homeSection',
          'aiDoctor',
          'marketing',
          'premium',
          'voiceAiMarketing',
        ]) ??
        _strings[languageCode]?[key] ??
        _strings[_fallback]?[key] ??
        _semanticFallbacks[languageCode]?[key] ??
        _semanticFallbacks[_fallback]?[key] ??
        _legacyFallbacks[languageCode]?[key] ??
        _legacyFallbacks[_fallback]?[key] ??
        key;
    if (languageCode != _fallback && _brokenTranslationMarker.hasMatch(value)) {
      return const AppLocalizations(_fallback).t(key);
    }
    return value;
  }

  String format(String key, Map<String, String> values) {
    var template = t(key);
    for (final entry in values.entries) {
      template = template.replaceAll('{${entry.key}}', entry.value);
    }
    return template;
  }

  String literal(String value) {
    if (value == 'marketingAboutText') return marketingAboutText();
    final translated = coreTranslation(languageCode, value, const [
          'auth',
          'voiceAiMarketing',
          'literal',
          'homeSection',
          'aiDoctor',
          'marketing',
          'premium',
          'full',
          'compact',
        ]) ??
        _strings[languageCode]?[value] ??
        value;
    if (languageCode != _fallback &&
        _brokenTranslationMarker.hasMatch(translated)) {
      return const AppLocalizations(_fallback).literal(value);
    }
    return translated;
  }

